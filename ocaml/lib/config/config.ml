type source = Default | File of string | Environment of string | Flag

let source_to_string = function
  | Default -> "default"
  | File path -> "file " ^ path
  | Environment name -> "environment " ^ name
  | Flag -> "command line"

type t = { values : (string * (string * source)) list; root : string option; cwd : string }

let find_setting key = List.find_opt (fun st -> st.key = key) settings

let edit_distance a b =
  let la = String.length a and lb = String.length b in
  let previous = Array.init (lb + 1) Fun.id and current = Array.make (lb + 1) 0 in
  for i = 1 to la do
    current.(0) <- i;
    for j = 1 to lb do
      let cost = if a.[i - 1] = b.[j - 1] then 0 else 1 in
      current.(j) <- min (min (previous.(j) + 1) (current.(j - 1) + 1)) (previous.(j - 1) + cost)
    done;
    Array.blit current 0 previous 0 (lb + 1)
  done;
  previous.(lb)

let nearest word candidates =
  let scored = List.map (fun c -> (edit_distance word c, c)) candidates in
  match List.sort compare scored with
  | (d, best) :: _ when d <= max 2 (String.length word / 3) -> Some best
  | _ -> None

let config_fault ?hint number message = Fault.make ?hint ~area:"CONFIG" ~number ~exit:Exit_code.Config message

let validate setting ~where raw =
  let bad expected =
    Error (config_fault 2 (Printf.sprintf "%s: '%s' must be %s, got '%s'" where setting.key expected raw))
  in
  match setting.kind with
  | String | Path -> Ok raw
  | Int -> (match int_of_string_opt raw with Some n when n >= 0 -> Ok (string_of_int n) | _ -> bad "a non-negative integer")
  | Float -> (match float_of_string_opt raw with Some f when f >= 0.0 -> Ok raw | _ -> bad "a non-negative number")
  | Bool ->
    (match String.lowercase_ascii raw with
     | "true" | "1" | "yes" | "on" -> Ok "true"
     | "false" | "0" | "no" | "off" -> Ok "false"
     | _ -> bad "true or false")
  | Enum choices -> if List.mem raw choices then Ok raw else bad ("one of " ^ String.concat ", " choices)

let home_dir getenv =
  match getenv "MAITHIC_HOME" with
  | Some dir when dir <> "" -> dir
  | _ ->
    (match getenv "XDG_CONFIG_HOME" with
     | Some dir when dir <> "" -> Fs.(dir / "maithic")
     | _ -> Fs.(Option.value (getenv "HOME") ~default:"." / ".config" / "maithic"))

let find_workspace ?(getenv = Sys.getenv_opt) dir =
  match getenv "MAITHIC_WORKSPACE" with
  | Some ws when ws <> "" -> Some ws
  | _ ->
    let rec up dir depth =
      if Fs.exists Fs.(dir / "maithic.toml") then Some dir
      else
        let parent = Filename.dirname dir in
        if parent = dir || depth > 64 then None else up parent (depth + 1)
    in
    up dir 0

(* Flattens the tables of a parsed file into dotted keys. *)
let rec flatten prefix = function
  | Json.Obj members ->
    List.concat_map (fun (k, v) -> flatten (if prefix = "" then k else prefix ^ "." ^ k) v) members
  | value -> [ (prefix, value) ]

let scalar_text = function
  | Json.String s -> Some s
  | Json.Int n -> Some (string_of_int n)
  | Json.Float f -> Some (Printf.sprintf "%g" f)
  | Json.Bool b -> Some (string_of_bool b)
  | _ -> None

let ( let* ) = Result.bind

let apply values setting ~where source raw =
  let* value = validate setting ~where raw in
  Ok ((setting.key, (value, source)) :: List.remove_assoc setting.key values)

let unknown_key ~where key =
  let hint = Option.map (Printf.sprintf "Did you mean '%s'?") (nearest key (List.map (fun st -> st.key) settings)) in
  Error (config_fault ?hint 1 (Printf.sprintf "%s: unknown setting '%s'" where key))

let load_file values path =
  if not (Fs.exists path) then Ok values
  else
    match Toml.parse_file path with
    | Error e -> Error (config_fault 3 e)
    | Ok doc ->
      List.fold_left
        (fun acc (key, value) ->
          let* values = acc in
          match find_setting key, scalar_text value with
          | None, _ -> unknown_key ~where:path key
          | Some _, None -> Error (config_fault 2 (Printf.sprintf "%s: '%s' must be a single value" path key))
          | Some setting, Some raw -> apply values setting ~where:path (File path) raw)
        (Ok values) (flatten "" doc)

let defaults = List.map (fun st -> (st.key, (st.default, Default))) settings
let of_defaults () = { values = defaults; root = None; cwd = Sys.getcwd () }

let load ?cwd ?(getenv = Sys.getenv_opt) ?(flags = []) ?files () =
  let cwd = match cwd with Some dir -> dir | None -> Sys.getcwd () in
  let root = find_workspace ~getenv cwd in
  let files =
    match files with
    | Some files -> files
    | None ->
      [ "/etc/maithic/maithic.toml"; Fs.(home_dir getenv / "config.toml") ]
      @ (match root with Some dir -> [ Fs.(dir / "maithic.toml") ] | None -> [])
  in
  let* values = List.fold_left (fun acc path -> Result.bind acc (fun v -> load_file v path)) (Ok defaults) files in
  let* values =
    List.fold_left
      (fun acc setting ->
        let* values = acc in
        match getenv setting.env with
        | Some raw when raw <> "" -> apply values setting ~where:("environment variable " ^ setting.env) (Environment setting.env) raw
        | _ -> Ok values)
      (Ok values) settings
  in
  let* values =
    List.fold_left
      (fun acc (key, raw) ->
        let* values = acc in
        match find_setting key with
        | None -> unknown_key ~where:"command line" key
        | Some setting -> apply values setting ~where:"command line" Flag raw)
      (Ok values) flags
  in
  Ok { values; root; cwd }

let lookup t key =
  match List.assoc_opt key t.values with
  | Some entry -> entry
  | None -> invalid_arg ("Config: unknown setting " ^ key)

let string t key = fst (lookup t key)
let string_opt t key = match string t key with "" -> None | v -> Some v
let int t key = int_of_string (string t key)
let float t key = float_of_string (string t key)
let bool t key = string t key = "true"
let source t key = snd (lookup t key)
let workspace t = t.root

let resolve_path t path =
  if path = "" || not (Filename.is_relative path) then path
  else Fs.(Option.value t.root ~default:t.cwd / path)

let to_json t =
  Json.Obj
    (List.map
       (fun st ->
         let value, src = lookup t st.key in
         (st.key, Json.Obj [ ("value", Json.String value); ("source", Json.String (source_to_string src)) ]))
       settings)

let kind_to_string = function
  | String -> "string"
  | Path -> "path"
  | Int -> "integer"
  | Float -> "number"
  | Bool -> "boolean"
  | Enum choices -> String.concat " \\| " (List.map (Printf.sprintf "`%s`") choices)

let reference_markdown () =
  let row st =
    Printf.sprintf "| `%s` | `%s` | %s | %s | %s |" st.key st.env (kind_to_string st.kind)
      (if st.default = "" then "(empty)" else "`" ^ st.default ^ "`")
      st.doc
  in
  String.concat "\n"
    ([ "| Setting | Environment variable | Type | Default | Meaning |"; "|---|---|---|---|---|" ] @ List.map row settings)
  ^ "\n"
