test_that("P01-05-01 prove runs are imported into validated tables", {
  runs <- read_prove_runs(demo_run_paths())
  expect_s3_class(runs, "maithic_prove_runs")
  expect_equal(runs$runs$provider, c("anthropic", "none"))
  expect_equal(runs$runs$model, c("m1", "none"))
  expect_equal(runs$runs$mode, c("live", "off"))
  expect_equal(runs$runs$calls, c(3, 0))
  expect_equal(runs$runs$failed_calls, c(1, 0))
  expect_equal(runs$runs$input_tokens, c(2500, 0))
  expect_equal(runs$runs$model_ms, c(2030, 0))
  expect_equal(runs$results$theorem, c("t1", "t2", "t3", "u1"))
  expect_equal(runs$results$proved, c(TRUE, TRUE, FALSE, TRUE))
  expect_equal(runs$results$attempts, c(2, 4, 2, 1))
  expect_equal(runs$results$lean_ms, c(52, 85, 503, 23))
  expect_equal(runs$results$recheck_ms, c(40, 60, NA, 20))
  expect_equal(runs$results$proof_steps, c(1, 4, 0, 1))
  expect_equal(runs$results$axioms[[2]], c("propext", "Classical.choice"))
  expect_equal(nrow(runs$attempts), 9)
  expect_equal(runs$attempts$error_class[1:2], c("tactic-failed", NA))
  expect_equal(nrow(runs$usage), 3)
  expect_equal(count_proof_steps(c("by simp; omega", "by\n  intro h\n  exact h", "", NA, "by first | simp | omega", "by simp <;> omega", "by_cases h : p")),
               c(2, 2, 0, 0, 1, 2, 1))

  expect_error(read_prove_runs(character()), "no run files")
  expect_error(read_prove_runs(file.path(tempdir(), "absent.json")), "file not found")
  expect_error(read_prove_runs(write_document(list(schema = "maithic.bench.run/1"))), "not a prove run")
  expect_error(read_prove_runs(write_prove_run(list(prove_result("a")), total = 2)), "stated total")
  expect_error(read_prove_runs(write_prove_run(list(prove_result("a")), verified = 0)), "verified results")
  expect_error(read_prove_runs(write_prove_run(list(prove_result("a", status = "proven")))), "unknown status 'proven'")
  expect_error(read_prove_runs(write_prove_run(list(prove_result("a"), prove_result("a")))), "reported twice")
  expect_error(read_prove_runs(write_prove_run(list(prove_result("")))), "names no theorem")
})

test_that("P01-05-01 the runs recorded in the repository are read as they are", {
  skip_if(is.null(fixture_root()), "the repository fixtures are not available")
  paths <- run_fixture(c("prove-even.json", "prove-triangle-anthropic.json", "prove-triangle-openai.json", "prove-triangle-xai.json"))
  runs <- read_prove_runs(paths)
  expect_equal(runs$runs$provider, c("none", "anthropic", "openai", "xai"))
  expect_true(all(runs$runs$mode == "replay"))
  expect_true(all(runs$results$proved))
  expect_equal(runs$results$proposer, c("portfolio", "model", "model", "model"))
  expect_equal(runs$runs$calls, c(0, 2, 2, 2))
  expect_true(all(runs$results$recheck_passed))
  expect_true(all(runs$results$lean_ms <= runs$results$elapsed_ms))
  expect_true(all(runs$usage$served_by == "replay"))
  expect_equal(sort(unique(runs$usage$purpose)), c("prove.propose", "prove.repair"))
})

test_that("P01-05-02 success rates come with Wilson intervals, overall and by group", {
  runs <- read_prove_runs(demo_run_paths())
  overall <- prover_success(runs)
  expect_equal(overall[c("n", "proved", "rate")], data.frame(n = 4L, proved = 3L, rate = 0.75))
  expect_equal(c(overall$lower, overall$upper), unlist(wilson_interval(3, 4)[c("lower", "upper")], use.names = FALSE))
  by_provider <- prover_success(runs, by = "provider")
  expect_equal(by_provider$provider, c("anthropic", "none"))
  expect_equal(by_provider$n, c(3, 1))
  expect_equal(by_provider$proved, c(2, 1))
  both <- prover_success(runs, by = c("file", "proposer"))
  expect_equal(both$proposer, c("", "model", "portfolio", "portfolio"))
  expect_equal(both$rate, c(0, 1, 1, 1))
  expect_error(prover_success(runs, by = "colour"), "no column named 'colour'")
  expect_error(prover_success(list()), "read_prove_runs")
})

test_that("P01-05-03 time to proof is summarised for the whole attempt, for Lean and for the re-check", {
  runs <- read_prove_runs(demo_run_paths())
  time <- prover_time(runs)
  expect_equal(time$metric, c("wall", "lean", "recheck"))
  expect_equal(time$n, c(4, 4, 3))
  expect_equal(time$median, c(500, 68.5, 40))
  expect_equal(time$max, c(2000, 503, 60))
  proved <- prover_time(runs, proved_only = TRUE)
  expect_equal(proved$median[proved$metric == "wall"], 100)
  grouped <- prover_time(runs, by = "provider", probs = 0.5)
  expect_equal(grouped$provider, rep(c("anthropic", "none"), each = 3))
  expect_equal(names(grouped), c("provider", "metric", "n", "median", "p50", "mean", "max"))
  expect_equal(grouped$median[grouped$provider == "none"], c(50, 23, 20))
})

test_that("P01-05-04 tokens and cost are counted per call and per proved theorem", {
  runs <- read_prove_runs(demo_run_paths())
  tokens <- prover_tokens(runs)
  expect_equal(tokens$calls, c(3, 0))
  expect_equal(tokens$tokens_per_call, c(1000, NA))
  expect_equal(tokens$tokens_per_proved, c(1500, 0))
  expect_equal(tokens$model_ms, c(2030, 0))
  expect_false("cost" %in% names(tokens))
  priced <- prover_tokens(runs, demo_prices)
  expect_equal(priced$cost, c(0.015, 0))
  expect_equal(priced$cost_per_proved, c(0.0075, 0))
  expect_error(prover_tokens(runs, demo_prices[2, ]), "no price for anthropic / m1")
})

