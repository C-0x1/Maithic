test_that("P01-05-06 failures are broken down by outcome and by error class", {
  failures <- prover_failures(read_prove_runs(demo_run_paths()))
  expect_equal(failures$kind, c("status", "status", rep("error_class", 4)))
  expect_equal(failures$name, c("verified", "failed", "tactic-failed", "timeout", "type-mismatch", "unclassified"))
  expect_equal(failures$count, c(3, 1, 3, 1, 1, 1))
  expect_equal(failures$share, c(0.75, 0.25, 0.5, 1 / 6, 1 / 6, 1 / 6))
  clean <- prover_failures(read_prove_runs(write_prove_run(list(prove_result("a", attempts = list(attempt(TRUE, 1)))))))
  expect_equal(clean$name, "verified")
})

