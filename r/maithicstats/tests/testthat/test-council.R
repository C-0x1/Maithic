test_that("P06-07-01 council sessions are loaded with their turns, messages and outcomes", {
  sessions <- read_council_sessions(demo_council_paths())
  expect_s3_class(sessions, "maithic_council_sessions")
  expect_equal(sessions$sessions$label, c("proved", "open"))
  expect_equal(sessions$sessions$theorem, c("t", "u"))
  expect_equal(sessions$sessions$status, c("verified", "formalized"))
  expect_equal(sessions$sessions$ending, c("settled", "rounds"))
  expect_equal(sessions$sessions$rounds, c(3, 1))
  expect_equal(sessions$sessions$with_model, c(TRUE, TRUE))
  expect_equal(sessions$sessions$turns, c(7, 4))
  expect_equal(sessions$sessions$messages, c(8, 3))
  expect_equal(sessions$sessions$items, c(7, 3))
  expect_equal(sessions$sessions$model_calls, c(4, 2))
  expect_equal(sessions$sessions$lean_calls, c(23, 20))
  expect_equal(sessions$sessions$seconds, c(1.5, 1.5))
  # The outcome: the round in which the proof Lean accepted was posted, and by whom.
  expect_equal(sessions$sessions$proof_round, c(2, NA))
  expect_equal(sessions$sessions$proof_author, c("prover", NA))

  expect_equal(nrow(sessions$turns), 11)
  expect_equal(sessions$turns$role[1:7], c("verifier", "researcher", "prover", "verifier", "critic", "prover", "verifier"))
  expect_equal(sessions$turns$task[1:5], c("examine", "research", "prove", "verify", "critique"))
  expect_equal(sessions$turns$round[1:7], c(0, 1, 1, 1, 1, 2, 2))
  expect_equal(sessions$turns$posted[1:7], c(0, 2, 1, 0, 1, 1, 0))
  expect_equal(sessions$turns$model_calls[1:7], c(0, 1, 1, 0, 1, 1, 0))
  expect_equal(sessions$turns$lean_calls[1:7], c(20, 1, 0, 1, 0, 0, 1))
  expect_equal(sessions$turns$status[9], "idle")
  expect_equal(sessions$turns$summary[3], "prover did prove")

  expect_equal(nrow(sessions$messages), 11)
  expect_equal(sessions$messages$seq[1:8], 1:8)
  expect_equal(sessions$messages$sender[3:6], c("researcher", "prover", "verifier", "critic"))
  expect_equal(sessions$messages$performative[3:6], c("inform", "propose", "verdict", "critique"))
  expect_equal(sessions$messages$recipients[c(1, 3)], c("researcher, prover", "prover, coordinator"))
  expect_equal(sessions$messages$refers[c(3, 8)], c(2, 2))

  expect_equal(nrow(sessions$items), 10)
  expect_equal(sessions$items$kind[1:7], c("statement", "claim", "definition", "note", "proof", "note", "proof"))
  expect_equal(sessions$items$author[3:7], c("researcher", "researcher", "prover", "critic", "prover"))
  expect_equal(sessions$items$checked[1:4], c(FALSE, FALSE, TRUE, FALSE))
  expect_equal(sessions$items$status[c(2, 9)], c("verified", "formalized"))
  expect_true(all(is.na(sessions$items$status[sessions$items$kind != "claim"])))
  expect_equal(sessions$items$examined[c(5, 7, 10)], c("rejected", "accepted", "rejected"))

  # What each role contributed, over both sessions.
  roles <- role_contributions(sessions)
  expect_equal(roles$role, c("researcher", "prover", "verifier", "critic"))
  expect_equal(roles$turns, c(2, 3, 5, 1))
  expect_equal(roles$messages, c(1, 3, 4, 1))
  expect_equal(roles$items, c(2, 3, 0, 1))
  expect_equal(roles$confirmed, c(1, 1, 0, 0))
  expect_equal(roles$model_calls, c(2, 3, 0, 1))
  expect_equal(roles$lean_calls, c(1, 0, 42, 0))

  # Sessions are labelled by the names of the paths, by the file names, or outright.
  paths <- unname(demo_council_paths())
  expect_equal(read_council_sessions(paths)$sessions$label, sub("\\.json$", "", basename(paths)))
  expect_equal(read_council_sessions(paths, label = c("first", "second"))$turns$label[c(1, 11)], c("first", "second"))
  expect_error(read_council_sessions(paths, label = "one"), "one label for each session")
  expect_error(read_council_sessions(character()), "no council sessions given")
  expect_error(read_council_sessions(tempfile(fileext = ".json")), "file not found")
  expect_error(read_council_sessions(write_document(list(schema = "maithic.mend.report/1"))), "is not a council session")
  expect_error(role_contributions(list()), "must come from read_council_sessions")

  # A session that contradicts itself is refused.
  broken <- function(change) {
    document <- jsonlite::fromJSON(demo_council_paths()[["proved"]], simplifyVector = FALSE)
    write_document(change(document))
  }
  expect_error(read_council_sessions(broken(function(d) { d$status <- "proved"; d })), "a session with the unknown status 'proved'")
  expect_error(read_council_sessions(broken(function(d) { d$ending$reason <- "tired"; d })), "a session with the unknown ending 'tired'")
  expect_error(read_council_sessions(broken(function(d) { d$turns[[2]]$role <- "judge"; d })), "a turn of the unknown role 'judge'")
  expect_error(read_council_sessions(broken(function(d) { d$messages[[2]]$seq <- 5; d })), "the messages are not in the order they were said")
  expect_error(read_council_sessions(broken(function(d) { d$messages[[4]]$performative <- "verdict"; d })), "a verdict that the verifier did not give")
  expect_error(read_council_sessions(broken(function(d) { d$board[[2]]$status <- "formalized"; d })), "the session is 'verified', and its claim is 'formalized'")
  expect_error(read_council_sessions(broken(function(d) { d$board[[7]]$examined <- "rejected"; d })), "the claim is 'verified', and 0 proof\\(s\\) were accepted by Lean")
})

test_that("P06-07-01 the session the repository keeps is read whole", {
  skip_if(is.null(fixture_root()), "the repository fixtures are not available")
  sessions <- read_council_sessions(file.path(fixture_root(), "council", "sum-odd.json"))
  expect_equal(sessions$sessions$theorem, "sumOdd_eq_square")
  expect_equal(sessions$sessions$status, "verified")
  expect_equal(sessions$sessions$ending, "settled")
  expect_equal(sessions$sessions$turns, 7)
  expect_equal(sessions$sessions$messages, 18)
  expect_equal(sessions$sessions$items, 11)
  expect_equal(sessions$sessions$model_calls, 4)
  expect_equal(sessions$sessions$lean_calls, 24)
  expect_equal(sessions$sessions$proof_round, 2)
  expect_equal(sessions$sessions$proof_author, "prover")
  expect_equal(sessions$turns$role, c("verifier", "researcher", "prover", "verifier", "critic", "prover", "verifier"))
  expect_equal(sessions$items$examined[sessions$items$kind == "proof"], c("rejected", "rejected", "accepted"))
  roles <- role_contributions(sessions)
  # Four of the researcher's five items are lemmas Lean confirmed; one of the prover's three proofs was accepted.
  expect_equal(roles$items, c(5, 3, 0, 1))
  expect_equal(roles$confirmed, c(4, 1, 0, 0))
  expect_equal(roles$model_calls, c(1, 2, 0, 1))
  expect_equal(roles$lean_calls, c(1, 0, 23, 0))
})
